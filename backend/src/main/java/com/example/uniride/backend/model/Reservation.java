package com.example.uniride.backend.model;

import com.example.uniride.backend.exception.ApiException;
import com.example.uniride.backend.exception.ErrorCode;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.Objects;
import java.util.UUID;

/**
 * Seat request of a passenger on a trip (docs/API.md §3.4). The id is the UUID generated by
 * the app, so {@code PUT /trips/{tripId}/reservations/{reservationId}} is idempotent.
 *
 * <p>The status only changes through {@link #accept}, {@link #reject} and {@link #cancel}, which
 * validate the transition and move the seat of the trip. Repeating a transition that already
 * happened does nothing (docs/API.md §1, idempotency).
 */
@Entity
@Table(name = "reservations", indexes = {
        @Index(name = "idx_reservations_trip", columnList = "trip_id"),
        @Index(name = "idx_reservations_passenger", columnList = "passenger_id"),
})
public class Reservation {

    @Id
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "trip_id", nullable = false)
    private Trip trip;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "passenger_id", nullable = false)
    private User passenger;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private ReservationStatus status;

    @Column(name = "reserved_at", nullable = false, updatable = false)
    private Instant reservedAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Reservation() {
    }

    /** New request, {@code PENDIENTE} until the driver answers. It does not take a seat yet. */
    public Reservation(UUID id, Trip trip, User passenger, Instant now) {
        this.id = Objects.requireNonNull(id);
        this.trip = Objects.requireNonNull(trip);
        this.passenger = Objects.requireNonNull(passenger);
        this.status = ReservationStatus.PENDIENTE;
        this.reservedAt = now;
        this.updatedAt = now;
    }

    /** {@code PENDIENTE} → {@code ACEPTADA}, taking a seat of the trip. */
    public void accept(Instant now) {
        if (status == ReservationStatus.ACEPTADA) {
            return;
        }
        requireStatus(ReservationStatus.PENDIENTE);
        trip.takeSeat(now);
        changeTo(ReservationStatus.ACEPTADA, now);
    }

    /** {@code PENDIENTE} → {@code RECHAZADA}. */
    public void reject(Instant now) {
        if (status == ReservationStatus.RECHAZADA) {
            return;
        }
        requireStatus(ReservationStatus.PENDIENTE);
        changeTo(ReservationStatus.RECHAZADA, now);
    }

    /** {@code PENDIENTE} or {@code ACEPTADA} → {@code CANCELADA}. An accepted one gives the seat back. */
    public void cancel(Instant now) {
        if (status == ReservationStatus.CANCELADA) {
            return;
        }
        if (!status.isActive() || trip.isClosed()) {
            throw new ApiException(ErrorCode.INVALID_STATUS_TRANSITION);
        }
        if (status == ReservationStatus.ACEPTADA) {
            trip.releaseSeat(now);
        }
        changeTo(ReservationStatus.CANCELADA, now);
    }

    public boolean belongsTo(UUID userId) {
        return passenger.getId().equals(userId);
    }

    public boolean isFor(Trip other) {
        return trip.getId().equals(other.getId());
    }

    private void requireStatus(ReservationStatus expected) {
        if (status != expected) {
            throw new ApiException(ErrorCode.INVALID_STATUS_TRANSITION);
        }
    }

    private void changeTo(ReservationStatus newStatus, Instant now) {
        status = newStatus;
        updatedAt = now;
    }

    public UUID getId() {
        return id;
    }

    public Trip getTrip() {
        return trip;
    }

    public User getPassenger() {
        return passenger;
    }

    public ReservationStatus getStatus() {
        return status;
    }

    public Instant getReservedAt() {
        return reservedAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
