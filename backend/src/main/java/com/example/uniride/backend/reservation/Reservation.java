package com.example.uniride.backend.reservation;

import com.example.uniride.backend.trip.Trip;
import com.example.uniride.backend.user.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.Instant;
import java.util.UUID;

/**
 * Seat request of a passenger on a trip (docs/API.md §3.4). The id is the UUID generated by
 * the app, so {@code PUT /trips/{tripId}/reservations/{reservationId}} is idempotent.
 */
@Entity
@Table(name = "reservations", indexes = {
        @Index(name = "idx_reservations_trip", columnList = "trip_id"),
        @Index(name = "idx_reservations_passenger", columnList = "passenger_id"),
})
public class Reservation {

    @Id
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "trip_id", nullable = false)
    private Trip trip;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "passenger_id", nullable = false)
    private User passenger;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private ReservationStatus status;

    @CreationTimestamp
    @Column(name = "reserved_at", nullable = false, updatable = false)
    private Instant reservedAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Reservation() {
    }

    /** New request, {@code PENDIENTE} until the driver answers (docs/API.md §6.1). */
    public Reservation(UUID id, Trip trip, User passenger) {
        this.id = id;
        this.trip = trip;
        this.passenger = passenger;
        this.status = ReservationStatus.PENDIENTE;
    }

    public UUID getId() {
        return id;
    }

    public Trip getTrip() {
        return trip;
    }

    public User getPassenger() {
        return passenger;
    }

    public boolean belongsTo(UUID userId) {
        return passenger.getId().equals(userId);
    }

    public ReservationStatus getStatus() {
        return status;
    }

    public void setStatus(ReservationStatus status) {
        this.status = status;
    }

    public Instant getReservedAt() {
        return reservedAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
