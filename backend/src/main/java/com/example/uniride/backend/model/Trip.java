package com.example.uniride.backend.model;

import com.example.uniride.backend.exception.ApiException;
import com.example.uniride.backend.exception.ErrorCode;
import jakarta.persistence.Column;
import jakarta.persistence.Embedded;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.Objects;
import java.util.UUID;

/**
 * Trip published by a driver (docs/API.md §3.3). The id is the UUID generated by the app, so
 * {@code PUT /trips/{tripId}} is idempotent.
 *
 * <p>The seats and the status only change through the methods of this class
 * ({@link #takeSeat}, {@link #releaseSeat}), which keep the invariants: {@code 0 <= availableSeats
 * <= totalSeats} and {@code COMPLETO} exactly when an open trip has no seats left.
 */
@Entity
@Table(name = "trips", indexes = {
        @Index(name = "idx_trips_departure", columnList = "departure_date, departure_time"),
        @Index(name = "idx_trips_updated_at", columnList = "updated_at"),
})
public class Trip {

    @Id
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "driver_id", nullable = false)
    private User driver;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "campus_code", nullable = false)
    private Campus campus;

    @Embedded
    private TripRoute route;

    @Embedded
    private TripSchedule schedule;

    @Column(name = "total_seats", nullable = false)
    private int totalSeats;

    @Column(name = "available_seats", nullable = false)
    private int availableSeats;

    /** Whole pesos, no decimals (docs/API.md §1). */
    @Column(name = "contribution_per_seat", nullable = false)
    private int contributionPerSeat;

    /** Copy of the driver's vehicle when publishing: a later change does not alter past trips. */
    @Embedded
    private Vehicle vehicle;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private TripStatus status;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    /** Used by the {@code updatedSince} filter of {@code GET /trips}. */
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Trip() {
    }

    /**
     * New trip: {@code ABIERTO}, with every seat available and the vehicle of the driver's
     * profile (docs/API.md §5.4). Fails if the driver has no vehicle.
     */
    public Trip(UUID id, User driver, Campus campus, TripRoute route, TripSchedule schedule,
                int totalSeats, int contributionPerSeat, Instant now) {
        if (!driver.hasVehicle()) {
            throw new ApiException(ErrorCode.VALIDATION_ERROR, "Para publicar un viaje tenés que cargar tu vehículo.");
        }
        this.id = Objects.requireNonNull(id);
        this.driver = driver;
        this.campus = Objects.requireNonNull(campus);
        this.route = Objects.requireNonNull(route);
        this.schedule = Objects.requireNonNull(schedule);
        this.totalSeats = totalSeats;
        this.availableSeats = totalSeats;
        this.contributionPerSeat = contributionPerSeat;
        this.vehicle = driver.getVehicle().copy();
        this.status = TripStatus.ABIERTO;
        this.createdAt = now;
        this.updatedAt = now;
    }

    /**
     * Takes one seat for an accepted reservation. The trip becomes {@code COMPLETO} at 0.
     *
     * @throws ApiException {@code NO_SEATS_AVAILABLE} without seats, {@code INVALID_STATUS_TRANSITION}
     *                      if the trip is finished or cancelled
     */
    public void takeSeat(Instant now) {
        if (isClosed()) {
            throw new ApiException(ErrorCode.INVALID_STATUS_TRANSITION);
        }
        if (availableSeats == 0) {
            throw new ApiException(ErrorCode.NO_SEATS_AVAILABLE);
        }
        availableSeats--;
        if (availableSeats == 0) {
            status = TripStatus.COMPLETO;
        }
        updatedAt = now;
    }

    /** Gives back the seat of an accepted reservation that was cancelled. A full trip opens again. */
    public void releaseSeat(Instant now) {
        if (availableSeats >= totalSeats) {
            throw new IllegalStateException("El viaje " + id + " ya tiene todas sus vacantes libres");
        }
        availableSeats++;
        if (status == TripStatus.COMPLETO) {
            status = TripStatus.ABIERTO;
        }
        updatedAt = now;
    }

    /**
     * Checks that a passenger can ask for a seat now.
     *
     * @throws ApiException {@code TRIP_NOT_OPEN} if the trip is finished, cancelled or already
     *                      left; {@code NO_SEATS_AVAILABLE} if it is full
     */
    public void requireOpenForRequests(Instant now) {
        if (isClosed() || hasDepartedAt(now)) {
            throw new ApiException(ErrorCode.TRIP_NOT_OPEN);
        }
        if (availableSeats == 0) {
            throw new ApiException(ErrorCode.NO_SEATS_AVAILABLE);
        }
    }

    /**
     * Checks that its reservations can still change (docs/API.md §6.3).
     *
     * @throws ApiException {@code INVALID_STATUS_TRANSITION} if the trip is finished or cancelled;
     *                      {@code TRIP_ALREADY_DEPARTED} if it already left
     */
    public void requireReservationsChangeable(Instant now) {
        requireReservationsChangeable(now, ErrorCode.TRIP_ALREADY_DEPARTED.defaultMessage());
    }

    /** Same as {@link #requireReservationsChangeable(Instant)}, with the message for a departed trip. */
    public void requireReservationsChangeable(Instant now, String departedMessage) {
        if (isClosed()) {
            throw new ApiException(ErrorCode.INVALID_STATUS_TRANSITION);
        }
        if (hasDepartedAt(now)) {
            throw new ApiException(ErrorCode.TRIP_ALREADY_DEPARTED, departedMessage);
        }
    }

    /**
     * Something that is part of the trip as the API shows it changed (for example, a request).
     * Moves {@code updatedAt}, so the {@code updatedSince} refresh of RF03 brings it again.
     */
    public void touch(Instant now) {
        updatedAt = now;
    }

    public boolean hasDepartedAt(Instant now) {
        return schedule.hasDepartedAt(now);
    }

    /** {@code FINALIZADO} or {@code CANCELADO}: no more changes of reservations. */
    public boolean isClosed() {
        return status.isClosed();
    }

    public boolean isDrivenBy(UUID userId) {
        return driver.getId().equals(userId);
    }

    public UUID getId() {
        return id;
    }

    public User getDriver() {
        return driver;
    }

    public Campus getCampus() {
        return campus;
    }

    public TripRoute getRoute() {
        return route;
    }

    public TripSchedule getSchedule() {
        return schedule;
    }

    public int getTotalSeats() {
        return totalSeats;
    }

    public int getAvailableSeats() {
        return availableSeats;
    }

    public int getContributionPerSeat() {
        return contributionPerSeat;
    }

    public Vehicle getVehicle() {
        return vehicle;
    }

    public TripStatus getStatus() {
        return status;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
