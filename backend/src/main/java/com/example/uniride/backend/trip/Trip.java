package com.example.uniride.backend.trip;

import com.example.uniride.backend.campus.Campus;
import com.example.uniride.backend.user.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalTime;
import java.util.UUID;

/**
 * Trip published by a driver (docs/API.md §3.3). The id is the UUID generated by the app,
 * so {@code PUT /trips/{tripId}} is idempotent. The vehicle data is copied from the driver's
 * profile when publishing, so a later change of vehicle does not alter past trips.
 */
@Entity
@Table(name = "trips", indexes = {
        @Index(name = "idx_trips_departure", columnList = "departure_date, departure_time"),
        @Index(name = "idx_trips_updated_at", columnList = "updated_at"),
})
public class Trip {

    @Id
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "driver_id", nullable = false)
    private User driver;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 10)
    private Direction direction;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "campus_code", nullable = false)
    private Campus campus;

    @Column(name = "meeting_point", nullable = false, length = 100)
    private String meetingPoint;

    @Column(name = "destination_neighborhood", nullable = false, length = 100)
    private String destinationNeighborhood;

    @Column(name = "destination_reference", length = 150)
    private String destinationReference;

    @Column(name = "departure_date", nullable = false)
    private LocalDate departureDate;

    @Column(name = "departure_time", nullable = false)
    private LocalTime departureTime;

    @Column(name = "estimated_arrival_time")
    private LocalTime estimatedArrivalTime;

    @Column(name = "total_seats", nullable = false)
    private int totalSeats;

    @Column(name = "available_seats", nullable = false)
    private int availableSeats;

    /** Whole pesos, no decimals (docs/API.md §1). */
    @Column(name = "contribution_per_seat", nullable = false)
    private int contributionPerSeat;

    @Column(name = "vehicle_model", nullable = false, length = 50)
    private String vehicleModel;

    @Column(name = "vehicle_color", nullable = false, length = 30)
    private String vehicleColor;

    @Column(name = "vehicle_plate", nullable = false, length = 10)
    private String vehiclePlate;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private TripStatus status;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    /** Used by the {@code updatedSince} filter of {@code GET /trips}. */
    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Trip() {
    }

    /** New trip: {@code ABIERTO} and with every seat available (docs/API.md §5.4). */
    public Trip(UUID id, User driver, Direction direction, Campus campus, String meetingPoint,
                String destinationNeighborhood, String destinationReference, LocalDate departureDate,
                LocalTime departureTime, LocalTime estimatedArrivalTime, int totalSeats,
                int contributionPerSeat, String vehicleModel, String vehicleColor, String vehiclePlate) {
        this.id = id;
        this.driver = driver;
        this.direction = direction;
        this.campus = campus;
        this.meetingPoint = meetingPoint;
        this.destinationNeighborhood = destinationNeighborhood;
        this.destinationReference = destinationReference;
        this.departureDate = departureDate;
        this.departureTime = departureTime;
        this.estimatedArrivalTime = estimatedArrivalTime;
        this.totalSeats = totalSeats;
        this.availableSeats = totalSeats;
        this.contributionPerSeat = contributionPerSeat;
        this.vehicleModel = vehicleModel;
        this.vehicleColor = vehicleColor;
        this.vehiclePlate = vehiclePlate;
        this.status = TripStatus.ABIERTO;
    }

    public UUID getId() {
        return id;
    }

    public User getDriver() {
        return driver;
    }

    public boolean isDrivenBy(UUID userId) {
        return driver.getId().equals(userId);
    }

    public Direction getDirection() {
        return direction;
    }

    public Campus getCampus() {
        return campus;
    }

    public String getMeetingPoint() {
        return meetingPoint;
    }

    public String getDestinationNeighborhood() {
        return destinationNeighborhood;
    }

    public String getDestinationReference() {
        return destinationReference;
    }

    public LocalDate getDepartureDate() {
        return departureDate;
    }

    public LocalTime getDepartureTime() {
        return departureTime;
    }

    public LocalTime getEstimatedArrivalTime() {
        return estimatedArrivalTime;
    }

    public int getTotalSeats() {
        return totalSeats;
    }

    public int getAvailableSeats() {
        return availableSeats;
    }

    public void setAvailableSeats(int availableSeats) {
        this.availableSeats = availableSeats;
    }

    public int getContributionPerSeat() {
        return contributionPerSeat;
    }

    public String getVehicleModel() {
        return vehicleModel;
    }

    public String getVehicleColor() {
        return vehicleColor;
    }

    public String getVehiclePlate() {
        return vehiclePlate;
    }

    public TripStatus getStatus() {
        return status;
    }

    public void setStatus(TripStatus status) {
        this.status = status;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
